/**
 * Report documents with ROF formatting (owner 2026-11-28): PDF (landscape A4) and Excel, the same content —
 * the ROF mark and name, the report's title and description, what it shows (source, filters), who generated it and when
 * (Kigali time), the summary, then the rows (the header repeated on every PDF page, page numbers, a confidentiality line).
 * Pure functions of their input: the service decides WHO may have the document and WHAT rows go in.
 */
import ExcelJS from 'exceljs';
import PDFDocument from 'pdfkit';

import { ROF_LOGO_PNG } from './rof-logo.js';

export type Cell = string | number | boolean | Date | null;

export interface ReportDocument {
  title: string;
  description: string | null;
  source: string;
  filters: string[];
  generatedBy: string;
  generatedAt: Date;
  headers: string[];
  rows: Cell[][];
  summary: SummaryGroup[];
}
export interface SummaryGroup { label: string; counts: Array<{ value: string; count: number }> }

const BRAND = '#00428C';
const BRAND_ARGB = 'FF00428C';
const INK = '#0F172A';
const MUTED = '#475569';
const LINE = '#CBD5E1';
const ZEBRA = '#F1F5F9';
export const CONFIDENTIAL = 'Confidential: contains student information. For authorised ROF staff and the people this report was shared with only.';

/** Kigali time, as people read it: 28 Nov 2026, 14:05. */
export function kigali(d: Date, withTime = true): string {
  return new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Africa/Kigali', day: 'numeric', month: 'short', year: 'numeric', ...(withTime && { hour: '2-digit', minute: '2-digit', hour12: false }),
  }).format(d);
}

/** A cell as text (Yes / No, dates in Kigali time, empty as an en dash). */
export function cellText(v: Cell): string {
  if (v === null || v === undefined || v === '') return '–';
  if (typeof v === 'boolean') return v ? 'Yes' : 'No';
  if (v instanceof Date) return kigali(v);
  return String(v);
}

export function renderPdf(doc: ReportDocument): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const pdf = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 36, bufferPages: true, info: { Title: doc.title, Author: 'Rwanda Olympiad Foundation', Creator: 'ROF LMS' } });
    const chunks: Buffer[] = [];
    pdf.on('data', (c: Buffer) => chunks.push(c));
    pdf.on('end', () => resolve(Buffer.concat(chunks)));
    pdf.on('error', reject);

    const left = pdf.page.margins.left;
    const width = pdf.page.width - pdf.page.margins.left - pdf.page.margins.right;
    const bottom = () => pdf.page.height - pdf.page.margins.bottom - 18;

    // ── Title block ──
    pdf.image(ROF_LOGO_PNG, left, 30, { width: 40, height: 40 });
    pdf.fillColor(BRAND).font('Helvetica-Bold').fontSize(9).text('RWANDA OLYMPIAD FOUNDATION', left + 52, 33);
    pdf.fillColor(INK).font('Helvetica-Bold').fontSize(17).text(doc.title, left + 52, 45, { width: width - 52 });
    let y = Math.max(pdf.y, 74) + 6;
    pdf.moveTo(left, y).lineTo(left + width, y).lineWidth(1.5).strokeColor(BRAND).stroke();
    y += 8;
    pdf.font('Helvetica').fontSize(9).fillColor(MUTED);
    const meta = [
      ...(doc.description ? [doc.description] : []),
      `Data: ${doc.source}`,
      `Filters: ${doc.filters.length ? doc.filters.join('; ') : 'none (every row you may see)'}`,
      `Generated by ${doc.generatedBy} on ${kigali(doc.generatedAt)} (Kigali time) · ${doc.rows.length} row${doc.rows.length === 1 ? '' : 's'}`,
    ];
    for (const line of meta) { pdf.text(line, left, y, { width }); y = pdf.y + 2; }

    // ── Summary: one small table per group, side by side ──
    if (doc.summary.length) {
      y += 6;
      pdf.font('Helvetica-Bold').fontSize(11).fillColor(INK).text('Summary', left, y);
      y = pdf.y + 4;
      const boxW = Math.min(170, (width - 12 * (doc.summary.length - 1)) / doc.summary.length);
      let tallest = y;
      doc.summary.forEach((g, i) => {
        const x = left + i * (boxW + 12);
        let yy = y;
        pdf.rect(x, yy, boxW, 16).fill(BRAND);
        pdf.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(8.5).text(g.label, x + 5, yy + 4, { width: boxW - 10, lineBreak: false, ellipsis: true });
        yy += 16;
        for (const [j, c] of g.counts.slice(0, 8).entries()) {
          if (j % 2) pdf.rect(x, yy, boxW, 13).fill(ZEBRA);
          pdf.fillColor(INK).font('Helvetica').fontSize(8).text(c.value, x + 5, yy + 3, { width: boxW - 45, lineBreak: false, ellipsis: true });
          pdf.font('Helvetica-Bold').text(String(c.count), x + boxW - 40, yy + 3, { width: 35, align: 'right' });
          yy += 13;
        }
        if (g.counts.length > 8) { pdf.fillColor(MUTED).font('Helvetica').fontSize(7.5).text(`+ ${g.counts.length - 8} more`, x + 5, yy + 2); yy += 12; }
        tallest = Math.max(tallest, yy);
      });
      y = tallest + 12;
    }

    // ── Rows ──
    const n = doc.headers.length || 1;
    // Column widths: by the longest text (header or a sample of cells), within bounds, scaled to the page width.
    const sample = doc.rows.slice(0, 200);
    pdf.font('Helvetica').fontSize(8);
    const natural = doc.headers.map((h, i) => Math.min(220, Math.max(40, pdf.widthOfString(h) + 12,
      ...sample.map((r) => pdf.widthOfString(cellText(r[i])) + 10))));
    const total = natural.reduce((a, b) => a + b, 0);
    const widths = natural.map((w) => (w / total) * width);
    const rowH = 15;
    const header = () => {
      pdf.rect(left, y, width, rowH + 2).fill(BRAND);
      let x = left;
      pdf.font('Helvetica-Bold').fontSize(8).fillColor('#FFFFFF');
      doc.headers.forEach((h, i) => { pdf.text(h, x + 4, y + 5, { width: widths[i] - 8, lineBreak: false, ellipsis: true }); x += widths[i]; });
      y += rowH + 2;
    };
    if (y + rowH * 3 > bottom()) { pdf.addPage(); y = pdf.page.margins.top; }
    header();
    if (!doc.rows.length) {
      pdf.font('Helvetica').fontSize(9).fillColor(MUTED).text('No rows match this report.', left + 4, y + 6);
    }
    doc.rows.forEach((r, ri) => {
      if (y + rowH > bottom()) { pdf.addPage(); y = pdf.page.margins.top; header(); }
      if (ri % 2) pdf.rect(left, y, width, rowH).fill(ZEBRA);
      let x = left;
      pdf.font('Helvetica').fontSize(8).fillColor(INK);
      r.forEach((v, i) => { pdf.text(cellText(v), x + 4, y + 4, { width: widths[i] - 8, lineBreak: false, ellipsis: true }); x += widths[i]; });
      pdf.moveTo(left, y + rowH).lineTo(left + width, y + rowH).lineWidth(0.3).strokeColor(LINE).stroke();
      y += rowH;
    });
    void n;

    // ── Footer on every page ──
    const range = pdf.bufferedPageRange();
    for (let i = 0; i < range.count; i++) {
      pdf.switchToPage(range.start + i);
      const fy = pdf.page.height - pdf.page.margins.bottom - 8;
      pdf.font('Helvetica').fontSize(7).fillColor(MUTED);
      pdf.text(CONFIDENTIAL, left, fy, { width: width - 90, lineBreak: false, ellipsis: true });
      pdf.text(`Page ${i + 1} of ${range.count}`, left + width - 80, fy, { width: 80, align: 'right', lineBreak: false });
    }
    pdf.end();
  });
}

export async function renderXlsx(doc: ReportDocument): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'ROF LMS';
  wb.company = 'Rwanda Olympiad Foundation';
  wb.created = doc.generatedAt;
  const logo = wb.addImage({ buffer: ROF_LOGO_PNG as unknown as ExcelJS.Buffer, extension: 'png' });
  const ws = wb.addWorksheet((doc.title.replace(/[*?:\\/[\]]/g, ' ').slice(0, 31).trim()) || 'Report', { views: [{ state: 'frozen', ySplit: 7 }] });
  const cols = Math.max(doc.headers.length, 4);
  ws.addImage(logo, { tl: { col: 0, row: 0 }, ext: { width: 44, height: 44 } });
  const titleRow = (r: number, text: string, font: Partial<ExcelJS.Font>) => {
    ws.mergeCells(r, 2, r, cols);
    const c = ws.getCell(r, 2);
    c.value = text; c.font = font; c.alignment = { vertical: 'middle', wrapText: false };
  };
  titleRow(1, 'RWANDA OLYMPIAD FOUNDATION', { bold: true, size: 9, color: { argb: BRAND_ARGB } });
  titleRow(2, doc.title, { bold: true, size: 15, color: { argb: 'FF0F172A' } });
  titleRow(3, `Data: ${doc.source}${doc.description ? ` · ${doc.description}` : ''}`, { size: 9, color: { argb: 'FF475569' } });
  titleRow(4, `Filters: ${doc.filters.length ? doc.filters.join('; ') : 'none (every row you may see)'}`, { size: 9, color: { argb: 'FF475569' } });
  titleRow(5, `Generated by ${doc.generatedBy} on ${kigali(doc.generatedAt)} (Kigali time) · ${doc.rows.length} rows · ${CONFIDENTIAL}`, { size: 9, italic: true, color: { argb: 'FF475569' } });
  ws.getRow(1).height = 18; ws.getRow(2).height = 22;
  const head = ws.getRow(7);
  doc.headers.forEach((h, i) => {
    const c = head.getCell(i + 1);
    c.value = h;
    c.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_ARGB } };
    c.alignment = { vertical: 'middle' };
    c.border = { bottom: { style: 'thin', color: { argb: BRAND_ARGB } } };
  });
  head.height = 20;
  doc.rows.forEach((r, ri) => {
    const row = ws.getRow(8 + ri);
    r.forEach((v, i) => {
      const c = row.getCell(i + 1);
      c.value = v === null ? null : typeof v === 'boolean' ? (v ? 'Yes' : 'No') : v;
      if (v instanceof Date) c.numFmt = 'dd mmm yyyy hh:mm';
      if (ri % 2) c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF1F5F9' } };
    });
  });
  if (doc.headers.length) ws.autoFilter = { from: { row: 7, column: 1 }, to: { row: 7 + Math.max(doc.rows.length, 1), column: doc.headers.length } };
  doc.headers.forEach((h, i) => {
    const longest = Math.max(h.length, ...doc.rows.slice(0, 500).map((r) => cellText(r[i]).length));
    ws.getColumn(i + 1).width = Math.min(48, Math.max(10, longest + 2));
  });

  if (doc.summary.length) {
    const s = wb.addWorksheet('Summary');
    s.addRow(['Summary', doc.title]).font = { bold: true, size: 13 };
    s.addRow([`Generated by ${doc.generatedBy} on ${kigali(doc.generatedAt)} (Kigali time)`]).font = { size: 9, italic: true };
    for (const g of doc.summary) {
      s.addRow([]);
      const h = s.addRow([g.label, 'Count']);
      h.eachCell((c) => { c.font = { bold: true, color: { argb: 'FFFFFFFF' } }; c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_ARGB } }; });
      for (const c of g.counts) s.addRow([c.value, c.count]);
    }
    s.getColumn(1).width = 40; s.getColumn(2).width = 12;
  }
  return Buffer.from(await wb.xlsx.writeBuffer());
}
