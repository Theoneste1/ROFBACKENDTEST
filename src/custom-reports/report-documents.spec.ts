import ExcelJS from 'exceljs';

import { cellText, codeLabel, documentCell, kigali, renderPdf, renderXlsx, type ReportDocument } from './report-documents.js';

const doc = (rows: number): ReportDocument => ({
  title: 'Submissions and corrections', description: 'Round 1', source: 'Test submissions (with corrections)', filters: ['Subject is Mathematics'],
  generatedBy: 'Ada Admin', generatedAt: new Date('2026-11-28T12:05:00Z'),
  headers: ['Student name', 'School', 'Submitted', 'Corrected', 'Correction reason'],
  rows: Array.from({ length: rows }, (_, i) => [`Student ${i}`, i % 2 ? 'Test School' : 'Other School', new Date('2026-11-27T08:00:00Z'), i % 3 === 0, i % 3 === 0 ? 'Chose the Junior test by mistake; should be Senior Mathematics' : null]),
  summary: [{ label: 'Status', counts: [{ value: 'Submitted', count: rows }] }],
});
/** The pages of a pdfkit document (its page objects). */
const pages = (pdf: Buffer) => (pdf.toString('latin1').match(/\/Type \/Page\b/g) ?? []).length;

describe('report documents (ROF formatting)', () => {
  it('values for people: Kigali time, Yes / No, an en dash for empty, codes as words, dates as dates', () => {
    expect(kigali(new Date('2026-11-28T12:05:00Z'))).toBe('28 Nov 2026, 14:05');
    expect([cellText(true), cellText(false), cellText(null), cellText('')]).toEqual(['Yes', 'No', '–', '–']);
    expect(codeLabel('MARKING_IN_PROGRESS')).toBe('Marking in progress');
    expect(documentCell('enum', 'AWAITING_SECOND_MARKING')).toBe('Awaiting second marking');
    expect(documentCell('date', '2026-11-28T12:05:00.000Z')).toEqual(new Date('2026-11-28T12:05:00Z'));
    expect(documentCell('text', 'SENIOR')).toBe('SENIOR');   // only enum fields are reworded
  });

  it('PDF: one page for a short report; a long one continues on numbered pages with no blank page', async () => {
    const short = await renderPdf(doc(3));
    expect(short.subarray(0, 5).toString()).toBe('%PDF-');
    expect(pages(short)).toBe(1);
    const long = await renderPdf(doc(150));
    const n = pages(long);
    expect(n).toBeGreaterThan(3);
    expect(n).toBeLessThan(10);   // ~25–30 rows a page: no page per row, no blank pages from the footer
  });

  it('PDF: an empty report says so', async () => {
    expect(pages(await renderPdf(doc(0)))).toBe(1);
  });

  it('Excel: ROF title lines, the header on row 7 in logo blue, frozen below it, filters on it, a Summary sheet', async () => {
    const wb = new ExcelJS.Workbook();
    await wb.xlsx.load((await renderXlsx(doc(4))) as never);
    const ws = wb.worksheets[0];
    expect(ws.getCell('B1').value).toBe('RWANDA OLYMPIAD FOUNDATION');
    expect(ws.getCell('B2').value).toBe('Submissions and corrections');
    expect(String(ws.getCell('B4').value)).toBe('Filters: Subject is Mathematics');
    expect(String(ws.getCell('B5').value)).toMatch(/^Generated by Ada Admin on 28 Nov 2026, 14:05 \(Kigali time\) · 4 rows · Confidential/);
    expect(ws.getRow(7).getCell(1).value).toBe('Student name');
    expect((ws.getRow(7).getCell(1).fill as ExcelJS.FillPattern).fgColor?.argb).toBe('FF00428C');
    expect(ws.views[0]).toMatchObject({ state: 'frozen', ySplit: 7 });
    expect(ws.autoFilter).toBeTruthy();
    expect(ws.getRow(8).getCell(3).value).toEqual(new Date('2026-11-27T08:00:00Z'));
    expect(ws.getRow(8).getCell(4).value).toBe('Yes');
    expect(ws.rowCount).toBe(7 + 4);
    expect(wb.getWorksheet('Summary')!.getCell('A4').value).toBe('Status');
    expect(wb.getWorksheet('Summary')!.getRow(5).values).toEqual([undefined, 'Submitted', 4]);
  });
});
