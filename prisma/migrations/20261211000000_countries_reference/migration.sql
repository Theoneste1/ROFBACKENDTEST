-- School.countryCode → Country: refused, changing nothing, while any school names a code that is not a country.
DO $$
DECLARE
  unknown text;
BEGIN
  SELECT string_agg(DISTINCT s."countryCode", ', ') INTO unknown
    FROM "School" s LEFT JOIN "Country" c ON c."code" = s."countryCode"
   WHERE c."code" IS NULL;
  IF unknown IS NOT NULL THEN
    RAISE EXCEPTION 'COUNTRY_REFERENCE_REFUSED: schools use country code(s) that are not ISO 3166-1 alpha-2: %. Correct them first; nothing was changed.', unknown;
  END IF;
END $$;

