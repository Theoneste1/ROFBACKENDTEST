-- Countries (design area 1 as simplified by the owner, 2026-11-19). ROF is a global Olympiad platform: one common
-- structure for every country (S1–S6; S1–S3 Junior, S4–S6 Senior); a country only identifies where a student, teacher,
-- coach or school is, never a level or division, and never blocks a registration.
-- Additive: one new table and one new foreign key. No existing column or row changes:
--   Country  every ISO 3166-1 alpha-2 code (the 249 that class-validator IsISO31661Alpha2 accepts — the codes every
--            country field already uses), its English name (CLDR) and international calling code (libphonenumber).
--   School.countryCode gets a foreign key to Country, AFTER a check that every school's code exists (refused otherwise).
-- Rwanda's Province → District → Sector → School directory is unchanged.
-- Rollback: docs/migrations/20261211000000_countries_reference.rollback.sql

